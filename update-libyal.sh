#!/usr/bin/env bash
# Regenerates libyal-versions.nix: for each libyal project, finds the newest
# release whose source tarball can still be downloaded and records its hash.
#
#   ./update-libyal.sh > libyal-versions.nix
#
# Needs: git, nix-prefetch-url (comes with Nix), network access.
set -u

# libbfio and libagdb are built from git tags in libyal/ and are not listed here.
projects="libesedb libevtx libevt libscca libmsiecf libvmdk libvhdi libvslvm"

echo "# Generated by update-libyal.sh on $(date -u +%F). Do not edit by hand."
echo "# Upstream deletes old release assets: re-run the script if a download 404s."
echo "mkLibyal: {"

for name in $projects; do
  echo "checking $name ..." >&2
  found=
  # newest tag first; the status prefix differs per project (alpha, experimental)
  for ver in $(git ls-remote --tags --refs "https://github.com/libyal/$name" \
                 | sed 's|.*refs/tags/||' | grep -E '^[0-9]{8}$' | sort -r); do
    for status in alpha experimental; do
      url="https://github.com/libyal/$name/releases/download/$ver/$name-$status-$ver.tar.gz"
      if sha=$(nix-prefetch-url "$url" 2>/dev/null); then
        echo "  $name = mkLibyal { name = \"$name\"; status = \"$status\"; version = \"$ver\"; sha256 = \"$sha\"; };"
        echo "  -> $name $status $ver" >&2
        found=1
        break 2
      fi
    done
  done
  if [ -z "$found" ]; then
    echo "  # $name: no downloadable release tarball found"
    echo "  !! $name: nothing found" >&2
  fi
done

echo "}"
